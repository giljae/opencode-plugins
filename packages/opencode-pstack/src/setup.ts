import { fileURLToPath } from "node:url";

import { registerCommands } from "./commands.ts";
import { readUpstreamManifest } from "./content.ts";
import type { CommandHost, ModelHost, SkillHost } from "./host.ts";
import { registerSetupCommand } from "./pstack-setup.ts";
import { registerSkills } from "./skills.ts";

export type Host = SkillHost & CommandHost & ModelHost;

export interface SetupOptions {
  bundleDir: string;
  agentId: string;
  targetDir: string;
  mapPath: string;
}

export interface SetupResult {
  skills: number;
  commands: number;
}

/** The vendored bundle shipped inside this package. */
export function defaultBundleDir(): string {
  return fileURLToPath(new URL("../vendor/pstack/", import.meta.url));
}

/**
 * Register pstack's skills, a command per skill, and the `/pstack-setup`
 * command. Agents are generated by `/pstack-setup`, not registered here.
 */
export async function runSetup(host: Host, options: SetupOptions): Promise<SetupResult> {
  readUpstreamManifest(options.bundleDir);
  const skills = await registerSkills(host, options.bundleDir);
  const commands = await registerCommands(host, options.bundleDir, options.agentId);
  await registerSetupCommand(host, {
    bundleDir: options.bundleDir,
    targetDir: options.targetDir,
    mapPath: options.mapPath,
  });
  return { skills, commands };
}
